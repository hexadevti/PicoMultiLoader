def main():
    for app, art in ICONS.items():
        rows = [r for r in art.strip('\n').split('\n')]
        if len(rows) != 32 or any(len(r) != 32 for r in rows):
            sys.exit('%s: the icon must be 32 rows of 32 characters (%d rows; widths %s)'
                     % (app, len(rows), sorted({len(r) for r in rows})))
        px = [[ROLE[c] for c in r] for r in rows]
        out = os.path.join(HERE, app, 'icon.bmp')
        write_icon(out, px)
        print(out)


if __name__ == '__main__':
    main()
